# Sourced by the build_ffmpeg_*.sh scripts. Trims FFmpeg down to what playing
# audio needs, since Songo never decodes video or images (tags and cover art
# are read by a separate library). The video, subtitle and image decoders were
# three quarters of the binary.
#
