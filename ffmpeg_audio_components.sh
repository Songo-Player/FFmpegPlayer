# the image ones (any container can carry audio, and embedded cover art is
# read inside the audio demuxers), bitstream filters and protocols, so network
# playback behaves the same as a full build.
#
# All three lists were made for FFmpeg n8.1.2. Revisit them when updating
# FFmpeg, as new components won't be built until they're added here.

